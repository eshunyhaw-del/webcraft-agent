// Validates benchmark run records and reports regressions between the latest two runs of each brief.
// Usage: node scripts/bench/report.mjs [runs-folder] [--write]
// --write saves the report to benchmarks/RESULTS.md. Exits 1 if a record is invalid or a regression is found.
// A regression is: a new critical defect, build or QA going from PASS to FAIL, or any score dropping by 1 or more.
import { readFileSync, readdirSync, existsSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { validate } from "../template/validate-manifest.mjs";
import { DIMENSIONS } from "./new-run.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const schema = JSON.parse(readFileSync(join(root, "schemas", "benchmark-run.schema.json"), "utf8"));
const total = (s) => { const v = Object.values(s).filter((x) => x !== null); return v.length ? v.reduce((a, b) => a + b, 0) : null; };

export function report(runsDir = join(root, "benchmarks", "runs")) {
  const invalid = [], runs = [];
  for (const f of existsSync(runsDir) ? readdirSync(runsDir).filter((f) => f.endsWith(".json")).sort() : []) {
    let r;
    try { r = JSON.parse(readFileSync(join(runsDir, f), "utf8")); } catch (e) { invalid.push(`${f}: ${e.message}`); continue; }
    const errs = validate(r, schema, schema, f);
    if (errs.length) invalid.push(...errs); else runs.push(r);
  }
  const byBrief = {};
  for (const r of runs) (byBrief[r.brief] ||= []).push(r);
  const rows = [], regressions = [];
  for (const [brief, list] of Object.entries(byBrief).sort()) {
    list.sort((a, b) => (a.date + a.runId).localeCompare(b.date + b.runId));
    const cur = list.at(-1), prev = list.length > 1 ? list.at(-2) : null;
    const notes = [];
    if (cur.criticalDefects.length) notes.push(`${cur.criticalDefects.length} critical defect(s)`);
    if (prev) {
      const newCrit = cur.criticalDefects.filter((d) => !prev.criticalDefects.includes(d));
      if (newCrit.length) regressions.push(`${brief}: new critical defect(s): ${newCrit.join("; ")}`);
      for (const k of ["build", "qa"]) if (prev[k].status === "PASS" && cur[k].status === "FAIL") regressions.push(`${brief}: ${k} went from PASS to FAIL`);
      for (const d of DIMENSIONS) {
        const a = prev.scores[d], b = cur.scores[d];
        if (a !== null && b !== null && b <= a - 1) regressions.push(`${brief}: ${d} dropped ${a} → ${b}`);
      }
      if (prev.promptVersion !== cur.promptVersion) notes.push("prompt changed");
    }
    const t = total(cur.scores), pt = prev && total(prev.scores);
    rows.push(`| ${brief} | ${cur.runId} | ${cur.stack || "-"} | ${cur.build.status} | ${cur.qa.status} | ${t ?? "-"}/60 | ${pt === null || pt === undefined || t === null ? "-" : (t - pt >= 0 ? "+" : "") + (t - pt)} | ${notes.join(", ") || "-"} |`);
  }
  const md = [
    "# Benchmark results",
    "",
    `Generated by \`node scripts/bench/report.mjs --write\` from ${runs.length} run record(s). Scores are out of 60 (12 dimensions × 5); a run with a critical defect fails regardless of score.`,
    "",
    "| Brief | Latest run | Stack | Build | QA | Score | Change | Notes |",
    "|---|---|---|---|---|---|---|---|",
    ...(rows.length ? rows : ["| (no runs yet) | | | | | | | |"]),
    "",
    "## Regressions",
    "",
    ...(regressions.length ? regressions.map((r) => "- " + r) : ["None."]),
    "",
  ].join("\n");
  return { runs: runs.length, invalid, regressions, markdown: md };
}

if (import.meta.url === pathToFileURL(process.argv[1] || "").href) {
  const dir = process.argv.slice(2).find((a) => !a.startsWith("--"));
  const r = report(dir);
  for (const e of r.invalid) console.log("INVALID " + e);
  console.log(r.markdown);
  if (process.argv.includes("--write")) writeFileSync(join(root, "benchmarks", "RESULTS.md"), r.markdown);
  process.exitCode = r.invalid.length || r.regressions.length ? 1 : 0;
}
